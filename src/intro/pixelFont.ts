export function textWidth(text: string): number {
  return text.length * 4 - 1
}

/** Draws text with its top-left corner at (x, y). Unknown characters are skipped. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string) {
  ctx.fillStyle = color
  let cx = x
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch]
    if (g) {
      for (let row = 0; row < 5; row++) {
        for (let col = 0; col < 3; col++) if (g[row][col] === '#') ctx.fillRect(cx + col, y + row, 1, 1)
      }
    }
    cx += 4
  }
}

/** Splits text into lines that fit within maxWidth pixels, breaking between words. */
export function wrapText(text: string, maxWidth: number): string[] {
  const maxChars = Math.max(1, Math.floor((maxWidth + 1) / 4))
  const lines: string[] = []
  let line = ''
  for (const word of text.split(' ')) {
    const next = line ? `${line} ${word}` : word
    if (next.length <= maxChars) line = next
    else {
      if (line) lines.push(line)
      line = word
    }
  }
  if (line) lines.push(line)
  return lines
}
